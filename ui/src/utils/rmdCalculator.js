const ageOnDate = (birthdateStr, onDate) => {
  if (!birthdateStr) return 0;
  const birthDate = new Date(birthdateStr);
  if (Number.isNaN(birthDate.getTime())) {
    return 0;
  }
  let age = onDate.getFullYear() - birthDate.getFullYear();
  if (
    onDate.getMonth() < birthDate.getMonth() ||
    (onDate.getMonth() === birthDate.getMonth() && onDate.getDate() < birthDate.getDate())
  ) {
    age -= 1;
  }
  return age;
};

const getDivisor = (ownerBirthdate, spouseBirthdate, year) => {
  const asOf = new Date(year, 11, 31);
  const ownerAge = ageOnDate(ownerBirthdate, asOf);
  let divisor = UNIFORM_TABLE[ownerAge];
  let tableUsed = 'uniform';

  if (spouseBirthdate) {
    const spouseAge = ageOnDate(spouseBirthdate, asOf);
    if (spouseAge + 10 <= ownerAge) {
      const jtRow = JOINT_LIFE_TABLE[ownerAge];
      if (jtRow && jtRow[spouseAge]) {
        divisor = jtRow[spouseAge];
        tableUsed = 'joint';
      }
    }
  }

  if (divisor == null) {
    divisor = Math.max(1.0, 27.4 - Math.max(0, ownerAge - 70) * 0.9);
  }
  return { divisor, tableUsed };
};

export const calculateRmd = (ownerBirthdate, balance, year, spouseBirthdate = null) => {
  if (!ownerBirthdate) {
    return { year, divisor: null, table_used: 'uniform', rmd_amount: 0 };
  }
  const { divisor, tableUsed } = getDivisor(ownerBirthdate, spouseBirthdate, year);
  const rmdAmount = divisor > 0 ? balance / divisor : balance;
  return {
    year,
    divisor,
    table_used: tableUsed,
    rmd_amount: rmdAmount,
  };
};
